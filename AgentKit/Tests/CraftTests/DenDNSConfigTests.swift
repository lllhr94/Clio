import Craft
import Foundation
import XCTest

final class DenDNSConfigTests: XCTestCase {
    func testNameserverValidationAcceptsIPv4AndIPv6AndZone() {
        XCTAssertTrue(DenDNSConfig.isValidNameserver("192.168.1.1"))
        XCTAssertTrue(DenDNSConfig.isValidNameserver(" 10.0.0.53 "))
        XCTAssertTrue(DenDNSConfig.isValidNameserver("2001:4860:4860::8888"))
        XCTAssertTrue(DenDNSConfig.isValidNameserver("fe80::1%en0"))
        XCTAssertTrue(DenDNSConfig.isValidNameserver("fe80::1%utun3"))

        XCTAssertFalse(DenDNSConfig.isValidNameserver(""))
        XCTAssertFalse(DenDNSConfig.isValidNameserver("999.1.1.1"))
        XCTAssertFalse(DenDNSConfig.isValidNameserver("1.1.1.1%en0"))
        XCTAssertFalse(DenDNSConfig.isValidNameserver("fe80::1%"))
        XCTAssertFalse(DenDNSConfig.isValidNameserver("fe80::1%en0\nsearch evil"))
        XCTAssertFalse(DenDNSConfig.isValidNameserver("dns.example.com"))
        XCTAssertFalse(DenDNSConfig.isValidNameserver("8.8.8.8; rm -rf /"))
    }

    func testParseCustomDNSListSeparatesValidAndInvalid() {
        let parsed = DenDNSConfig.parseCustomDNSList("1.1.1.1, bad.host\n1.1.1.1; fe80::1%en0 999.0.0.1")
        XCTAssertEqual(parsed.valid, ["1.1.1.1", "fe80::1%en0"])
        XCTAssertEqual(parsed.invalid, ["bad.host", "999.0.0.1"])
    }

    func testSearchDomainSanitizationRejectsInjectionAndInvalidLabels() {
        let domains = DenDNSConfig.sanitizeSearchDomains([
            "corp.local.",
            "home.arpa",
            "CORP.LOCAL",
            "bad domain.local",
            "evil\nnameserver 6.6.6.6",
            "-leading.local",
            "trailing-.local",
            String(repeating: "a", count: 64) + ".local",
            "ok-sub.example.org"
        ])
        XCTAssertEqual(domains, ["corp.local", "home.arpa", "ok-sub.example.org"])
    }

    func testAutoModePreservesValidExistingWithoutPublicDNSFallback() {
        let existing = "# Generated by Clio Den (auto)\nnameserver 10.20.0.1\n"
        let decision = DenDNSConfig.renderResolvConf(
            mode: .auto,
            systemServers: [],
            customServers: [],
            searchDomains: ["lan"],
            existingContent: existing
        )
        XCTAssertEqual(decision, .preserveExisting)

        let fresh = DenDNSConfig.renderResolvConf(
            mode: .auto,
            systemServers: [],
            customServers: [],
            searchDomains: [],
            existingContent: nil
        )
        guard case .write(let body) = fresh else {
            return XCTFail("Expected write when no file exists yet")
        }
        XCTAssertFalse(body.contains("nameserver "))
        XCTAssertFalse(body.contains("8.8.8.8"))
        XCTAssertFalse(body.contains("1.1.1.1"))
    }

    func testCustomModeOverridesSystemDNSAndPreservesSearchDomains() {
        let decision = DenDNSConfig.renderResolvConf(
            mode: .custom,
            systemServers: ["192.168.1.1"],
            customServers: ["10.0.0.2", "fe80::2%en0"],
            searchDomains: ["office.internal", "bad;inject"],
            existingContent: nil
        )
        XCTAssertEqual(
            decision,
            .write("# Generated by Clio Den (custom)\nsearch office.internal\nnameserver 10.0.0.2\nnameserver fe80::2%en0\n")
        )
    }

    func testAtomicWriteCreatesReadableFileAndOverwritesCleanly() throws {
        let dir = FileManager.default.temporaryDirectory
            .appendingPathComponent("DenDNSConfigTests-\(UUID().uuidString)", isDirectory: true)
        defer { try? FileManager.default.removeItem(at: dir) }

        let target = dir.appendingPathComponent("resolv.conf", isDirectory: false)
        try DenDNSConfig.atomicWriteResolvConf(content: "nameserver 192.168.1.1\n", to: target)
        XCTAssertEqual(try String(contentsOf: target, encoding: .utf8), "nameserver 192.168.1.1\n")

        try DenDNSConfig.atomicWriteResolvConf(content: "nameserver 10.0.0.1\n", to: target)
        XCTAssertEqual(try String(contentsOf: target, encoding: .utf8), "nameserver 10.0.0.1\n")

        let entries = try FileManager.default.contentsOfDirectory(atPath: dir.path)
        XCTAssertEqual(entries, ["resolv.conf"])
    }

    func testThermalForkLimitsCoverAllStates() {
        XCTAssertEqual(DenThermalForkLimit.limit(for: .nominal), DenThermalForkLimit(perSecond: 400, burst: 80))
        XCTAssertEqual(DenThermalForkLimit.limit(for: .fair), DenThermalForkLimit(perSecond: 250, burst: 50))
        XCTAssertEqual(DenThermalForkLimit.limit(for: .serious), DenThermalForkLimit(perSecond: 120, burst: 25))
        XCTAssertEqual(DenThermalForkLimit.limit(for: .critical), DenThermalForkLimit(perSecond: 60, burst: 15))
    }
}
